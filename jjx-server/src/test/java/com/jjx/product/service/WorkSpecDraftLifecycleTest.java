        var products = mock(IProductService.class);
        Product product = new Product(); product.setProductId(1L); product.setProductCode("P1");
        var productVo = new com.jjx.product.domain.vo.ProductVo(); productVo.setProductId(1L); productVo.setProductCode("P1");
        ProductFullVO full = new ProductFullVO(); full.setProduct(productVo);
