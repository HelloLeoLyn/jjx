-- 多资源齐套缺口台账（dev-20261126-002）
CREATE TABLE IF NOT EXISTS print_kit_shortage (
  id BIGINT NOT NULL AUTO_INCREMENT,
  scope VARCHAR(10) NOT NULL COMMENT 'ORDER 工单 / PRODUCT 产品预检',
  order_id BIGINT NOT NULL DEFAULT 0,
  order_no VARCHAR(64) NULL,
  product_id BIGINT NOT NULL DEFAULT 0,
  routing_item_id BIGINT NOT NULL DEFAULT 0,
  process_name VARCHAR(100) NULL,
  resource_type VARCHAR(20) NOT NULL COMMENT 'MATERIAL / SCREEN_PLATE / DIE / DOC',
  resource_key VARCHAR(64) NOT NULL COMMENT '资源标识（物料ID/版本ID…）',
  resource_code VARCHAR(100) NULL,
  resource_name VARCHAR(200) NULL,
  need_qty DECIMAL(18,4) NOT NULL DEFAULT 0,
  available_qty DECIMAL(18,4) NOT NULL DEFAULT 0,
  gap_qty DECIMAL(18,4) NOT NULL DEFAULT 0,
  unit VARCHAR(20) NULL,
  status TINYINT NOT NULL DEFAULT 0 COMMENT '0 待处理 / 1 已关闭',
  owner VARCHAR(64) NULL,
  first_found_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  last_check_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  last_notified_at DATETIME(3) NULL,
  closed_reason VARCHAR(200) NULL,
  closed_by VARCHAR(64) NULL,
  closed_at DATETIME(3) NULL,
  active_marker TINYINT GENERATED ALWAYS AS (IF(status=0,1,NULL)) STORED,
  create_by VARCHAR(64) NULL,
  create_time DATETIME(3) NULL,
  update_by VARCHAR(64) NULL,
  update_time DATETIME(3) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_print_kit_active (scope, product_id, order_id, routing_item_id, resource_type, resource_key, active_marker),
  KEY idx_print_kit_status (status, last_check_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='印刷多资源齐套缺口';
